/**
 * Bundle `src/client.js` into the single browser file the host serves.
 * Run with `npm run build`; the result is committed so the profile link keeps
 * working without a build step at install time.
 */

import { build } from 'esbuild';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));

await build({
  absWorkingDir: root,
  entryPoints: ['src/client.js'],
  outfile: 'client.js',
  bundle: true,
  format: 'iife',
  target: ['chrome120'],
  platform: 'browser',
  charset: 'utf8',
  legalComments: 'none',
  minify: false,
  treeShaking: true,
  define: {
    __RG_VERSION__: JSON.stringify(pkg.version),
  },
  banner: {
    js: `/*! ${pkg.name} v${pkg.version} — built from src/, do not edit this file directly */`,
  },
});

const output = await stat(path.join(root, 'client.js'));
console.log(`built client.js (${(output.size / 1024).toFixed(1)} kB) for ${pkg.name}@${pkg.version}`);
